-- ─────────────────────────────────────────────────────────────────────────────
-- cron 실행 기록 자동 정리
--
-- 🐛 문제: 푸시 발송 cron 이 1분마다 도는데, pg_cron 은 실행할 때마다 기록을
--    cron.job_run_details 에 남기고 **스스로 지우지 않습니다.**
--
--    실측: 27일 만에 41,469행 / 53MB. DB 전체 68MB 중 78% 가 이 로그였고,
--          실제 앱 데이터는 15MB 뿐이었습니다.
--          하루 약 1,572행 = 2MB → 월 60MB 증가.
--          무료 플랜의 DB 한도 500MB 를 약 7개월 뒤 넘겨 읽기 전용으로 전환될
--          상황이었습니다(그때부터는 출석 체크도 글쓰기도 전부 실패합니다).
--
-- → 7일치만 남기고 매일 정리합니다. 실행 로그라 지워도 앱 동작에는 영향이 없고,
--   문제가 생겼을 때 들여다볼 최근 기록은 넉넉히 남습니다.
--
-- 적용 시점에 기존 41,469행을 10,115행으로 줄이고 vacuum full 로 공간을 회수해
-- DB 가 68MB → 20MB 가 되었습니다.
--
-- 시각은 베트남 기준 새벽(UTC 19:40 = 현지 02:40)으로 잡아, 성도들이 쓰지 않는
-- 시간대에 돌게 합니다. 다른 cron 들과 분(minute)을 겹치지 않게 두었습니다.
-- ─────────────────────────────────────────────────────────────────────────────

select cron.unschedule('purge-cron-history')
where exists (select 1 from cron.job where jobname = 'purge-cron-history');

select cron.schedule(
  'purge-cron-history',
  '40 19 * * *',
  $$ delete from cron.job_run_details where end_time < now() - interval '7 days' $$
);
